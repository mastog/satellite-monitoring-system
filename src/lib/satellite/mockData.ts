/**
 * Generate mock debris field
 */
export function generateMockDebris(count: number): SatelliteData[] {
  const debris: SatelliteData[] = [];
  for (let i = 0; i < count; i++) {
    const inclination = Math.random() * 180 - 90;
    const lng = Math.random() * 360 - 180;
    const alt = 200 + Math.random() * 2000;
    debris.push({
      id: `debris-${i}`,
      name: `DEBRIS ${10000 + i}`,
      noradId: 90000 + i,
      lat: inclination,
      lng,
      alt,
      velocity: 6.5 + Math.random() * 2,
      type: "debris",
    });
  }
  return debris;
}

